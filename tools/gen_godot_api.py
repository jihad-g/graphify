#!/usr/bin/env python3
"""Regenerate graphify/extractors/_godot_api.py from Godot's API dumps.

    git clone --depth 1 --filter=blob:none --sparse https://github.com/godotengine/godot-cpp
    cd godot-cpp && git sparse-checkout set gdextension
    python tools/gen_godot_api.py path/to/godot-cpp/gdextension

Collects every method name of every engine class and built-in type, plus the
global utility functions, unioned across all extension_api-4-*.json files.
"""
import glob
import json
import sys
from pathlib import Path

src = Path(sys.argv[1])
names: set[str] = set()
versions = []
for f in sorted(glob.glob(str(src / "extension_api-4-*.json"))):
    api = json.loads(Path(f).read_text())
    versions.append(Path(f).stem.replace("extension_api-", ""))
    for sec in ("builtin_classes", "classes"):
        for c in api[sec]:
            for m in c.get("methods") or []:
                names.add(m["name"])
    for u in api.get("utility_functions") or []:
        names.add(u["name"])

lines, line = [], "    "
for n in sorted(names):
    tok = repr(n) + ", "
    if len(line) + len(tok) > 88:
        lines.append(line.rstrip())
        line = "    "
    line += tok
lines.append(line.rstrip())

out = Path(__file__).resolve().parents[1] / "graphify" / "extractors" / "_godot_api.py"
out.write_text(
    '"""Godot engine method names, used to keep engine calls out of the graph.\n\n'
    f"Generated by tools/gen_godot_api.py from godot-cpp extension_api {versions[0]}..{versions[-1]}\n"
    "(the official GDExtension API dumps). Names only. A duck-typed `x.is_empty()`\n"
    "is far more likely Array/String.is_empty than a user method of the same name,\n"
    'so the GDScript resolver never binds these by name alone.\n"""\n\n'
    "GODOT_METHODS: frozenset[str] = frozenset({\n" + "\n".join(lines) + "\n})\n"
)
print(f"{len(names)} names -> {out}")
